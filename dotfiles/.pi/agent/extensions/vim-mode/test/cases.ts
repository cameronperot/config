/**
 * The command case matrix and the manifest of implemented commands.
 *
 * Every case starts in normal mode. Expectations are written by hand from Vim's documentation
 * and checked against Neovim by `oracle.test.ts`, except for cases flagged `pi`, which cover
 * Pi integrations that Neovim does not share.
 */

import type { Mode } from "../protocol.ts";

export interface Case {
	name: string;
	/** The manifest command this case covers. */
	command: string;
	/** Buffer before the keys; `|` marks the cursor. */
	buffer: string;
	/** Keys in Vim notation. */
	keys: string;
	/** Buffer after the keys; `|` marks the cursor. */
	expect: string;
	/** Mode after the keys; normal when omitted. */
	mode?: Mode;
	/** The keys carry a count. */
	counted?: boolean;
	/** Why Neovim differs: the case is excluded from the oracle. */
	pi?: string;
}

export interface CommandEntry {
	command: string;
	/** The command takes a count. */
	countable: boolean;
}

